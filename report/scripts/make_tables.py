"""
Write ``numbers.tex`` (one macro per number quoted in the text) and the LaTeX
tables in ``tables/`` from the measurement files in ``results/``.
"""
import sys
import json
import datetime
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from style import REPORT, RESULTS, TABLES, REDUX, DATASETS, NO_OBJECT  # noqa: E402

ENOISE = (4.67, 5.06)
EGAIN = (1.65, 1.47)
PUBLISHED_FAST = (7.0, 7.2)


def load(name):
    with open(RESULTS / name) as fh:
        return json.load(fh)


def fmt(x, nd=2):
    return f'{x:.{nd}f}'


def pm(v, e, nd=2):
    return f'\\num{{{v:.{nd}f} \\pm {e:.{nd}f}}}'


def write_table(name, body):
    (TABLES / f'{name}.tex').write_text(body)
    print(f'wrote tables/{name}.tex')


class Numbers:
    def __init__(self):
        self.lines = ['% Generated by scripts/make_tables.py -- do not edit']

    def __setitem__(self, key, value):
        self.lines.append(f'\\newcommand{{\\{key}}}{{{value}}}')

    def write(self):
        (REPORT / 'numbers.tex').write_text('\n'.join(self.lines) + '\n')
        print('wrote numbers.tex')


def epoch_label(key):
    ep, night = key.split(' ')
    y, m = ep.split('-')
    return datetime.date(int(y), int(m), 1).strftime('%Y %b')


