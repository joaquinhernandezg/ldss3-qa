def detector_tables(N):
    det = load('detector.json')
    bias = det['bias']
    keys = sorted(bias)
    N['nBiasEpochs'] = str(len(keys))
    from style import RAW
    N['nFramesSurvey'] = str(len(list(RAW.glob('*/ccd*c1.fits'))))

    # Read noise table
    rows = []
    for k in keys:
        b = bias[k]
        rows.append(f"{epoch_label(k)} & {b['1']['n_frames']} & "
                    f"{pm(b['1']['ron_e'], b['1']['ron_e_std'])} & {fmt(b['1']['ron_oscan_e'])} & "
                    f"{pm(b['2']['ron_e'], b['2']['ron_e_std'])} & {fmt(b['2']['ron_oscan_e'])} \\\\")
    r1 = np.array([bias[k]['1']['ron_e'] for k in keys])
    r2 = np.array([bias[k]['2']['ron_e'] for k in keys])
    m1, s1 = r1.mean(), r1.std(ddof=1) / np.sqrt(r1.size)
    m2, s2 = r2.mean(), r2.std(ddof=1) / np.sqrt(r2.size)
    N['ronAmpOne'] = pm(m1, s1)
    N['ronAmpTwo'] = pm(m2, s2)
    exc = 100 * (np.array([m1 / ENOISE[0], m2 / ENOISE[1]]) - 1)
    N['ronExcessRange'] = f'{exc.min():.0f}--{exc.max():.0f}'
    write_table('readnoise', r'''\begin{table}[t]
  \centering\small
  \caption{Read noise (\si{\electron}) per epoch, from bias-pair differences
    (mean $\pm$ standard deviation over pairs) and from the overscan scatter, for
    the gains in the \code{EGAIN} keyword. The published Fast-mode values are 7.0
    and 7.2~\si{\electron}; the \code{ENOISE} keyword gives 4.67 and
    5.06~\si{\electron}.}
  \label{tab:ron}
  \begin{tabular}{lrcccc}
    \toprule
    & & \multicolumn{2}{c}{Amplifier 1} & \multicolumn{2}{c}{Amplifier 2} \\
    \cmidrule(lr){3-4}\cmidrule(lr){5-6}
    Epoch & $N_{\rm bias}$ & pairs & overscan & pairs & overscan \\
    \midrule
''' + '\n'.join('    ' + r for r in rows) + f'''
    \\midrule
    Mean & & {pm(m1, s1)} & & {pm(m2, s2)} & \\\\
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
''')

    # Gain table
    ptc = det['ptc']
    rows, g1, g2, e1, e2, rej = [], [], [], [], [], []
    for k in sorted(ptc):
        p = ptc[k]
        night, grism, aper, filt, t = k.split(' ')
        ok = all(np.isfinite(p[a]['gain']) and p[a]['n_points'] >= 10 for a in '12')
        # A set is kept if both gains are within 10% of EGAIN.  Larger departures
        # are produced by lamp or illumination changes between the two exposures
        # of a pair, which the PTC cannot separate from shot noise.
        ok &= all(abs(p[a]['gain'] / EGAIN[int(a) - 1] - 1) < 0.10 for a in '12')
        mark = '' if ok else '$^\\dagger$'
        rows.append(f"{night.replace('_', r'\_')} & {grism} & {aper.replace('_', r'\_')} & {t} & "
                    f"{p['1']['n_pairs']} & {pm(p['1']['gain'], p['1']['gain_err'], 3)} & "
                    f"{pm(p['2']['gain'], p['2']['gain_err'], 3)}{mark} \\\\")
        if ok:
            g1.append(p['1']['gain']); e1.append(p['1']['gain_err'])
            g2.append(p['2']['gain']); e2.append(p['2']['gain_err'])
        else:
            rej.append(k)
    g1, g2 = np.array(g1), np.array(g2)
    # Scatter between sets dominates the formal errors, so quote the mean and the
    # standard error of the mean.
    G1, G2 = g1.mean(), g2.mean()
    E1, E2 = g1.std(ddof=1) / np.sqrt(g1.size), g2.std(ddof=1) / np.sqrt(g2.size)
    N['gainAmpOne'] = pm(G1, E1)
    N['gainAmpTwo'] = pm(G2, E2)
    N['nPtcRejected'] = str(len(rej))
    N['gainAgreement'] = f'{100 * max(abs(G1 / EGAIN[0] - 1), abs(G2 / EGAIN[1] - 1)):.0f}'
    best = max((k for k in ptc if k not in rej),
               key=lambda k: ptc[k]['1']['n_points'] + ptc[k]['2']['n_points'])
    night, grism, aper, filt, t = best.split(' ')
    N['ptcBest'] = f"{grism} {aper.replace('_', r'\_')} flats of {night.replace('_', r'\_')} ({t})"
    (RESULTS / 'ptc_best.txt').write_text(best)
    write_table('gain', r'''\begin{table}[t]
  \centering\small
  \caption{Gain (\si{\electron\per\adu}) from photon-transfer curves of flat pairs.
    Uncertainties are bootstrap estimates for each set. Sets marked $\dagger$
    depart from \code{EGAIN} by more than 10\,\% on at least one amplifier,
    because the lamp or illumination changed between the exposures of a pair, and
    are excluded from the mean.}
  \label{tab:gain}
  \begin{tabular}{llllrcc}
    \toprule
    Night & Grism & Slit/mask & $t_{\rm exp}$ & Pairs & Amp.~1 & Amp.~2 \\
    \midrule
''' + '\n'.join('    ' + r for r in rows) + f'''
    \\midrule
    \\multicolumn{{5}}{{l}}{{Mean of accepted sets}} & {pm(G1, E1)} & {pm(G2, E2)} \\\\
    \\multicolumn{{5}}{{l}}{{\\code{{EGAIN}}}} & 1.65 & 1.47 \\\\
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
''')

    # Bias levels and residuals
    lv = det['overscan_level']
    lev1 = np.array([lv[k]['1'][0] for k in lv])
    lev2 = np.array([lv[k]['2'][0] for k in lv])
    N['biasLevelSpread'] = f'{max(np.ptp(lev1), np.ptp(lev2)):.0f}'
    N['biasLevelNightly'] = f'{max(max(v["1"][1], v["2"][1]) for v in lv.values()):.0f}'
    prof = np.load(RESULTS / 'bias_profiles.npz')
    good = np.ones(2048, bool)
    for c1, c2 in det['bpm_ranges']:
        good[c1:c2 + 1] = False
    good[:20] = good[-20:] = False
    resid = max(np.max(np.abs(prof[k][good] - np.median(prof[k][good]))) for k in prof.files)
    N['biasResidMax'] = f'{np.ceil(resid):.0f}'

    # Persistent bad columns outside the mask
    from collections import Counter
    c = Counter(x for v in det['bad_column_candidates'].values() for x in v)
    pers = sorted(k for k, n in c.items() if n >= 4)
    inb = lambda x: any(a <= x <= b for a, b in det['bpm_ranges'])      # noqa: E731
    extra = [x for x in pers if not inb(x)]
    lo = [x for x in extra if x < 1024]
    hi = [x for x in extra if x >= 1024]
    N['edgeExtraOne'] = f'{min(lo)}--{max(lo)}' if len(lo) > 1 else (str(lo[0]) if lo else '--')
    N['edgeExtraTwo'] = f'{min(hi)}--{max(hi)}' if len(hi) > 1 else (str(hi[0]) if hi else '--')
    rows = []
    for c1, c2 in det['bpm_ranges']:
        n = c2 - c1 + 1
        amp = 1 if c2 < 1024 else 2
        rows.append(f'{c1}--{c2} & {n} & {amp} \\\\' if n > 1 else f'{c1} & 1 & {amp} \\\\')
    half = (len(rows) + 1) // 2
    body = []
    for i in range(half):
        r2_ = rows[i + half].rstrip('\\ ') if i + half < len(rows) else '& &'
        body.append(rows[i].rstrip('\\ ') + ' & ' + r2_ + ' \\\\')
    write_table('bpm', r'''\begin{table}[t]
  \centering\small
  \caption{Columns masked by default, in pixels of the trimmed, unbinned frame
    (spatial axis; amplifier~1 is 0--1023).}
  \label{tab:bpm}
  \begin{tabular}{lrclrc}
    \toprule
    Columns & $N$ & Amp. & Columns & $N$ & Amp. \\
    \midrule
''' + '\n'.join('    ' + r for r in body) + r'''
    \bottomrule
  \end{tabular}
\end{table}
''')

    # Dark current
    dk = det['dark']
    rates = [dk[n][a]['rate_e_hr'] for n in dk for a in '12']
    N['darkRate'] = f'{np.min(rates):.1f}--{np.max(rates):.1f}' if np.ptp(rates) > 0.2 \
        else f'{np.mean(rates):.1f}'
    ex = sorted({t for n in dk for t in dk[n]['1']['exptimes']})
    N['darkExptimes'] = '--'.join(f'{t:.0f}' for t in (ex[0], ex[-1])) if len(ex) > 1 else f'{ex[0]:.0f}'

    # Saturation and frames
    N['satLevel'] = f'{65535 * min(EGAIN):.0f}'


